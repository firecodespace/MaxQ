"""The benchmark mission suite (WP2-12): what every system is measured on.

The suite is DECLARED, not generated by a loop over whatever data happens to be present,
because a reader has to be able to see what is in it and why. Twenty-four missions: four
(profile, vehicle, pad) combinations, three launch windows each, two payload masses each.

What varies, and why each matters
---------------------------------
* **profile** -- `crew_iss` carries the 4.0 g acceleration limit and needs a crew-rated
  vehicle; `cargo_iss` does not. Only `falcon9_block5` is crew-rated, so every crew mission
  flies it. That is a property of the library, not a preference.
* **vehicle** -- `falcon9_block5` (sim error +11.2% against published payload),
  `antares_230plus` (+15.0%), `atlas_v_401` (-25.0%). Atlas V is the vehicle the simulator
  models worst and whose missions are hardest to make feasible. It is in the suite
  deliberately: a benchmark made only of missions we can already solve measures nothing.
* **pad** -- `mars_lp0a` sits at 37.84 N against 28.5-28.6 N for the Cape pads, so Antares
  missions carry a real plane-change penalty rather than a nominal one.
* **window** -- the phase angle sets how far the chaser has to catch up, which is the whole
  phasing problem. Twelve distinct windows are used, and the twelve are partitioned so that
  **no window appears in more than one split** (see `protocol.py`). Each split still spans
  the phase circle: train covers 10.8-282.1 deg, val 77.9-349.1, test 13.5-259.1.
* **payload** -- a light and a heavy case per combination, as a fraction of the vehicle's
  PUBLISHED payload-to-LEO. Never the simulated figure: scoring against our own model's
  output would make the suite a measurement of itself.

GEO and MEO are absent. `data/results/windows_geo_comm_*.json` and `..._meo_gps_*.json`
exist, but `MissionEnv` only flies a co-planar phasing and approach to an orbiting target, so
a GEO mission would be scored against physics that is not there. WP2-15 adds them. Until
then the suite covers what the environment can actually fly, and says so here rather than
quietly including missions whose numbers would be meaningless.

Nothing here is random. `missions()` returns the same twenty-four mission_request dicts on
every call and on every machine, and `protocol.py` hashes them.

Owner: Yash (lane: benchmarks/). Read-only to any agent -- see `benchmarks/hof.py`.
"""

from __future__ import annotations

import json
from functools import cache, lru_cache
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

SUITE_ID = "suite_v1"

#: Payload masses as a fraction of the vehicle's PUBLISHED payload-to-LEO figure.
PAYLOAD_FRACTIONS = {"light": 0.35, "heavy": 0.70}

#: The four (profile, vehicle, pad) combinations, each with three windows: one per split, in
#: the order (train, val, test). The twelve window ids are all distinct, which is what makes
#: the splits window-disjoint. Phase angles in the comments come from
#: data/results/windows_{profile}_cape_canaveral.json; the runner reads the real window data
#: rather than trusting these.
COMBINATIONS: tuple[dict[str, Any], ...] = (
    {
        "profile": "crew_iss", "rocket_id": "falcon9_block5", "pad_id": "ksc_lc39a", "crew": 4,
        "windows": {"train": "w0", "val": "w1", "test": "w2"},  # 10.8 / 77.9 / 101.0 deg
    },
    {
        "profile": "cargo_iss", "rocket_id": "falcon9_block5", "pad_id": "ccsfs_slc40", "crew": 0,
        "windows": {"train": "w3", "val": "w4", "test": "w5"},  # 167.4 / 192.0 / 259.1 deg
    },
    {
        "profile": "cargo_iss", "rocket_id": "antares_230plus", "pad_id": "mars_lp0a", "crew": 0,
        "windows": {"train": "w6", "val": "w7", "test": "w8"},  # 282.1 / 349.1 / 13.5 deg
    },
    {
        "profile": "cargo_iss", "rocket_id": "atlas_v_401", "pad_id": "ccsfs_slc41", "crew": 0,
        "windows": {"train": "w9", "val": "w10", "test": "w11"},  # 80.7 / 104.0 / 170.4 deg
    },
)

SPLIT_NAMES = ("train", "val", "test")

#: Every system gets the same budget on every mission. A benchmark where one system may run
#: more simulations than another measures the budget, not the system.
BUDGET_MAX_ATTEMPTS = 120
BUDGET_MAX_WALL_S = 1800.0

#: Fixes the environment's own stochastic choices. Each system additionally runs several
#: protocol seeds -- see `protocol.SYSTEM_SEEDS`.
MISSION_SEED = 20261112

ISS_NORAD_ID = 25544


@cache
def _vehicle(rocket_id: str) -> dict[str, Any]:
    path = ROOT / "data" / "rockets" / f"{rocket_id}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def _objective(vehicle: dict[str, Any]) -> dict[str, Any]:
    """The objective every suite mission is scored with.

    `fuel_ref_kg` is the vehicle's total propellant load and `prop_orbit_ref_kg` its upper
    stage's load, so both fuel terms read as a fraction of a real tank rather than of an
    arbitrary constant. The weights are the project defaults and are part of the protocol:
    changing any of them changes what every recorded cost means, so they are inside the hash.
    """
    stages = vehicle["stages"]
    return {
        "w_fuel": 1.0,
        "w_prop_orbit": 1.0,
        "w_time": 0.5,
        "fuel_ref_kg": float(sum(s["prop_kg"] for s in stages)),
        "prop_orbit_ref_kg": float(stages[-1]["prop_kg"]),
        "time_ref_s": 86400.0,
    }


_SHORT = {"falcon9_block5": "f9", "antares_230plus": "an", "atlas_v_401": "av"}
_PROF = {"crew_iss": "crew", "cargo_iss": "cargo"}


def mission_id(profile: str, rocket_id: str, window_id: str, payload_key: str) -> str:
    """Stable, readable, and derived only from the four things that vary."""
    return f"msn_bench_{_PROF[profile]}_{_SHORT[rocket_id]}_{window_id}_{payload_key}"


@lru_cache(maxsize=1)
def missions() -> tuple[dict[str, Any], ...]:
    """The twenty-four suite missions, in a fixed order, identical on every call."""
    out: list[dict[str, Any]] = []
    for combo in COMBINATIONS:
        vehicle = _vehicle(combo["rocket_id"])
        published = float(vehicle["payload_to_leo_kg_published"])
        for split in SPLIT_NAMES:
            window_id = combo["windows"][split]
            for payload_key in ("light", "heavy"):
                out.append(
                    {
                        "schema_version": 1,
                        "id": mission_id(
                            combo["profile"], combo["rocket_id"], window_id, payload_key
                        ),
                        "profile": combo["profile"],
                        "payload": {
                            "mass_kg": round(published * PAYLOAD_FRACTIONS[payload_key], 1),
                            "crew": combo["crew"],
                        },
                        "rocket_id": combo["rocket_id"],
                        "pad_id": combo["pad_id"],
                        "target": {"norad_id": ISS_NORAD_ID},
                        "window_id": window_id,
                        "constraints_profile": (
                            "crew_default" if combo["profile"] == "crew_iss" else "cargo_default"
                        ),
                        "objective": _objective(vehicle),
                        "budget": {
                            "max_attempts": BUDGET_MAX_ATTEMPTS,
                            "max_wall_s": BUDGET_MAX_WALL_S,
                        },
                        "seed": MISSION_SEED,
                    }
                )
    return tuple(out)


def mission_ids() -> tuple[str, ...]:
    return tuple(m["id"] for m in missions())


def mission_by_id(mid: str) -> dict[str, Any]:
    for m in missions():
        if m["id"] == mid:
            return m
    raise KeyError(f"{mid!r} is not a suite mission. Known: {list(mission_ids())}")


def split_of(mid: str) -> str:
    """Which split a mission belongs to, derived from the declaration above.

    The assignment lives in COMBINATIONS, not in a stored list, so a mission cannot end up in
    two splits and a split cannot silently gain a mission. `protocol.splits()` builds the
    lists from this.
    """
    m = mission_by_id(mid)
    for combo in COMBINATIONS:
        if (
            combo["profile"] == m["profile"]
            and combo["rocket_id"] == m["rocket_id"]
            and combo["pad_id"] == m["pad_id"]
        ):
            for split, window_id in combo["windows"].items():
                if window_id == m["window_id"]:
                    return split
    raise KeyError(f"{mid!r} matches no declared combination")  # unreachable via missions()
